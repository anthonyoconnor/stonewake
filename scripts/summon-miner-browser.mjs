import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL ?? 'msedge' });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${process.env.GAME_URL ?? 'http://127.0.0.1:5173'}/?scenario=economy&paused=1`);
  await page.waitForFunction(() => window.strongholdDev?.version === 1);
  await page.getByRole('button', { name: 'Dwarfs', exact: true }).click();
  assert.equal(await page.locator('#buy-miner').count(), 0);
  assert(!(await page.locator('#panel').textContent()).includes('Recruit a Miner'));
  await page.getByRole('button', { name: 'Spells', exact: true }).click();
  const cast = page.locator('[data-cast="summon-miner"]');
  assert.equal(await cast.textContent(), 'Cast · 75 gold');
  assert.equal(await page.locator('[data-research="summon-miner"]').count(), 0);
  const initial = await page.evaluate(() => window.strongholdDev.state());
  await cast.click();
  await page.waitForFunction(() => document.querySelector('[data-cast="summon-miner"]').textContent === 'Cast · 100 gold');
  await cast.click();
  const after = await page.evaluate(() => window.strongholdDev.state());
  assert.equal(after.agents.length, initial.agents.length + 2);
  assert.equal(after.spent - initial.spent, 175);
  assert.equal(after.researchOrders?.length ?? 0, 0);
  await page.locator('[data-spell="dwarf-haste"]').click();
  assert(await page.locator('[data-research="dwarf-haste"]').isVisible());
  await page.locator('[data-spell="summon-miner"]').click();
  assert.equal(await cast.textContent(), 'Cast · 125 gold');
  await page.locator('[data-spell-details="summon-miner"]').scrollIntoViewIfNeeded();
  mkdirSync('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/summon-miner.png' });
  await page.evaluate(() => window.strongholdDev.load('stronghold'));
  await page.getByRole('button', { name: 'Spells', exact: true }).click();
  assert(await cast.isDisabled());
  assert.match(await page.locator('#summon-miner-status').textContent(), /bed|Kitchen/);
  assert.deepEqual(errors, []);
  console.log('Summon Miner browser checks passed: no old recruitment controls, innate casting, exact escalating charges, research switching and missing-support feedback.');
} finally { await browser.close(); }
